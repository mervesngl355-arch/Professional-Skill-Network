    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            Path p = Paths.get("c:\\files2\\educationskills.dat");
            ObjectInputStream ois = new ObjectInputStream(new FileInputStream(p.toFile()));
            EducationSkillsClass es = (EducationSkillsClass) ois.readObject();
            String department = es.getDepartment();
            ois.close();
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            Connection con = DatabaseConnection.getConnection();
            String sql;
            if (jCheckBox1.isSelected()) {
                sql = "select * from professionals "
                        + "where department=? "
                        + "and status='Available'";
            } else {
                sql = "select * from professionals "
                        + "where position=? and company=?";

            }
            PreparedStatement ps = con.prepareStatement(sql);
            if (jCheckBox1.isSelected()) {
                ps.setString(1, department);
            } else {
                ps.setString(1, jComboBox1.getSelectedItem().toString());
                ps.setString(2, jComboBox2.getSelectedItem().toString());
            }
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {

                Object row[] = {
                    rs.getString("name"),
                    rs.getString("university"),
                    rs.getString("company"),
                    rs.getString("position"),
                    rs.getString("status")
                };
                dtm.addRow(row);
            }

            rs.close();
            ps.close();
            con.close();

            jTextField1.setText(
                    String.valueOf(dtm.getRowCount()));

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, e);

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        try {

            int row = jTable1.getSelectedRow();
            String name = jTable1.getValueAt(row, 0).toString();

            Connection con = DatabaseConnection.getConnection();

            String sql = "select * from professionals " + "where name=?";

            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, name);
            ResultSet rs = ps.executeQuery();
            DefaultListModel model = new DefaultListModel();

            if (rs.next()) {

                model.addElement(
                        "Skill 1: "
                        + rs.getString("skill1"));

                model.addElement(
                        "Skill 2: "
                        + rs.getString("skill2"));

                model.addElement(
                        "Skill 3: "
                        + rs.getString("skill3"));

                model.addElement(
                        "Language: "
                        + rs.getString("language1"));

                model.addElement(
                        "Level: "
                        + rs.getString("language_level1"));

                model.addElement(
                        "Trait: "
                        + rs.getString("trait1"));

                model.addElement(
                        "About: "
                        + rs.getString("about"));

            }

            jList1.setModel(model);

            rs.close();
            ps.close();
            con.close();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, e);

        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {

            int row = jTable1.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(null, "Please select a professional");
                return;
            }
            String name = jTable1.getValueAt(row, 0).toString();
            String company = jTable1.getValueAt(row, 2).toString();
            String position = jTable1.getValueAt(row, 3).toString();
            int option = JOptionPane.showConfirmDialog(
                    this,
                    "Do you want to send "
                    + "automatic networking message?",
                    "CareerLink Network",
                    JOptionPane.YES_NO_OPTION);

            String message = "";

            if (option == JOptionPane.YES_OPTION) {
                message = "Hello " + name + ",\n\n"
                        + "I reviewed your profile at "
                        + company + " for the "
                        + position + " position.\n\n"
                        + "Your experience looks very "
                        + "impressive.\n\n"
                        + "I would like to connect with "
                        + "you for networking and "
                        + "career advice.\n\n"
                        + "Best regards.";
            } else {
                message = JOptionPane.showInputDialog(this, "Write your own message:");
                if (message == null || message.isEmpty()) {
                    return;
                }
            }
            JOptionPane.showMessageDialog(
                    this,
                    "Message Sent Successfully\n\n"
                    + message,
                    "CareerLink Message",
                    JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try {
            int row = jTable1.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(null, "Please select a professional");
                return;
            }

            String name = jTable1.getValueAt(row, 0).toString();
            String company = jTable1.getValueAt(row, 2).toString();
            String position = jTable1.getValueAt(row, 3).toString();
            Connection con = DatabaseConnection.getConnection();
            String sql = "insert into network_requests "
                    + "(user_id,professional_name,company,"
                    + "position_name,request_status) "
                    + "values (?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(sql);
            ps.setInt(1, LoginRegister.currentUserId);
            ps.setString(2, name);
            ps.setString(3, company);
            ps.setString(4, position);
            ps.setString(5, "Pending");
            ps.executeUpdate();

            ps.close();
            con.close();

            JOptionPane.showMessageDialog(
                    null,
                    "Connection Request Sent Successfully",
                    "CareerLink Network",
                    JOptionPane.INFORMATION_MESSAGE
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, e);

        }
    }//GEN-LAST:event_jButton3ActionPerformed

