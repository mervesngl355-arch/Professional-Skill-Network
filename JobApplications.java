    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:

        try {
            Path p = Paths.get("c:\\files2\\educationskills.dat");
            ObjectInputStream ois = new ObjectInputStream(new FileInputStream(p.toFile()));
            EducationSkillsClass es = (EducationSkillsClass) ois.readObject();

            String department = es.getDepartment();
            ois.close();

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();

            dtm.setRowCount(0);

            Connection con = DatabaseConnection.getConnection();

            String sql = "";
            if (jCheckBox2.isSelected()) {
                sql = "select * from jobs "
                        + "where department=?";
            } else {
                sql = "select * from jobs "
                        + "where department=? "
                        + "and position_name=? "
                        + "and work_mode=? "
                        + "and company=? "
                        + "and employment_type=?";

                if (jCheckBox1.isSelected()) {
                    sql += " and city='" + selectedCity + "'";
                }
            }

            PreparedStatement ps = con.prepareStatement(sql);

            if (jCheckBox2.isSelected()) {

                ps.setString(1, department);

            } else {

                ps.setString(1, department);
                ps.setString(2, jComboBox1.getSelectedItem().toString());
                ps.setString(3, jComboBox2.getSelectedItem().toString());
                ps.setString(4, jComboBox3.getSelectedItem().toString());
                ps.setString(5, jComboBox4.getSelectedItem().toString());
            }

            ResultSet rs = ps.executeQuery();

            while (rs.next()) {
                Object row[] = {
                    rs.getString("company"),
                    rs.getString("position_name"),
                    rs.getString("work_mode"),
                    rs.getString("employment_type"),
                    rs.getInt("match_score"),
                    rs.getString("status")
                };

                dtm.addRow(row);
            }

            rs.close();
            ps.close();
            con.close();
            JOptionPane.showMessageDialog(null, "Jobs Listed");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }


    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {

            int row = jTable1.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(null, "Please select a job");
                return;

            }

            String company = jTable1.getValueAt(row, 0).toString();

            String position = jTable1.getValueAt(row, 1).toString();

            Connection con = DatabaseConnection.getConnection();

            String sql = "select * from jobs "
                    + "where company=? "
                    + "and position_name=?";

            PreparedStatement ps = con.prepareStatement(sql);

            ps.setString(1, company);

            ps.setString(2, position);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {

                String details = "Company: "
                        + rs.getString("company")
                        + "\n\nPosition: "
                        + rs.getString("position_name")
                        + "\n\nSalary: "
                        + rs.getString("salary")
                        + "\n\nExperience Level: "
                        + rs.getString("experience_level")
                        + "\n\nRequired Skills: "
                        + rs.getString("required_skills")
                        + "\n\nCity: "
                        + rs.getString("city")
                        + "\n\nDetails: "
                        + rs.getString("job_details");

                JOptionPane.showMessageDialog(null, details, "Job Details", JOptionPane.INFORMATION_MESSAGE);

            }

            rs.close();
            ps.close();
            con.close();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, e);

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {

            int row = jTable1.getSelectedRow();

            if (row == -1) {
                JOptionPane.showMessageDialog(null, "Please select a job");
                return;

            }

            String company = jTable1.getValueAt(row, 0).toString();
            String position = jTable1.getValueAt(row, 1).toString();
            Path eduPath = Paths.get("c:\\files2\\educationskills.dat");

            ObjectInputStream ois = new ObjectInputStream(new FileInputStream(eduPath.toFile())
            );

            EducationSkillsClass es = (EducationSkillsClass) ois.readObject();

            ois.close();

            if (company.equals("Google") && es.getProjectCount() < 5) {
                JOptionPane.showMessageDialog(null, "Google requires minimum 5 projects"
                );
                return;
            }

            if (company.equals("Microsoft") && !es.isClubMember()) {
                JOptionPane.showMessageDialog(null, "Microsoft requires club membership"
                );
                return;
            }

            if (company.equals("Oracle") && es.getGpa() < 3.0) {

                JOptionPane.showMessageDialog(null, "Oracle requires GPA 3.0+"
                );
                return;
            }
            if (company.equals("Meta")
                    && !es.getLanguageLevel().equals("C1")
                    && !es.getLanguageLevel().equals("C2")
                    && !es.getLanguageLevel().equals("Native")) {

                JOptionPane.showMessageDialog(null, "Meta requires advanced English");

                return;
            }
            if (company.equals("Amazon")
                    && !es.getDegreeProgram().equals("Master")
                    && !es.getDegreeProgram().equals("PhD")) {

                JOptionPane.showMessageDialog(null, "Amazon requires Master or PhD");
                return;
            }
            if (position.equals("AI Engineer")
                    && es.getProjectCount() < 8) {

                JOptionPane.showMessageDialog(null, "AI Engineer requires minimum 8 projects");
                return;
            }
            if (position.equals("Backend Developer")
                    && !es.getSkillLevel().equals("Advanced")
                    && !es.getSkillLevel().equals("Expert")) {

                JOptionPane.showMessageDialog(null, "Backend Developer requires Advanced skill level");
                return;
            }
            if (company.equals("Google")
                    && es.getClubRole().equals("Member")) {

                JOptionPane.showMessageDialog(null, "Google prefers leadership experience");
                return;
            }
            if (position.equals("Corporate Lawyer")
                    && es.getLanguageLevel().equals("A1")) {

                JOptionPane.showMessageDialog(null, "Corporate Lawyer requires better English");

                return;
            }
            Connection con = DatabaseConnection.getConnection();
            String countSql = "select count(*) from job_applications "
                    + "where user_id=? and company=?";

            PreparedStatement cps = con.prepareStatement(countSql);
            cps.setInt(1, LoginRegister.currentUserId);
            cps.setString(2, company);

            ResultSet crs = cps.executeQuery();
            if (crs.next()) {
                if (crs.getInt(1) >= 2) {
                    JOptionPane.showMessageDialog(null, "Maximum 2 applications allowed");
                    return;
                }
            }
            if (company.equals("Google")
                    && !es.getUniversityName().equals("ITU")
                    && !es.getUniversityName().equals("METU")) {

                JOptionPane.showMessageDialog(null, "Google accepts selected universities");
                return;
            }
            if (jComboBox4.getSelectedItem()
                    .toString().equals("Internship")
                    && !es.isCurrentlyEnrolled()) {

                JOptionPane.showMessageDialog(null, "Internship requires student status");
                return;
            }
            if (es.getCertificatePath() == null
                    || es.getCertificatePath().isEmpty()) {

                JOptionPane.showMessageDialog(null, "Certificate required");
                return;
            }
            String checkSql
                    = "select * from job_applications "
                    + "where user_id=? "
                    + "and company=? "
                    + "and position_name=?";
            PreparedStatement checkPs = con.prepareStatement(checkSql);

            checkPs.setInt(1, LoginRegister.currentUserId);
            checkPs.setString(2, company);
            checkPs.setString(3, position);

            ResultSet checkRs = checkPs.executeQuery();
            if (checkRs.next()) {
                JOptionPane.showMessageDialog(null, "You already applied");
                return;
            }
            JobApplicationClass app = new JobApplicationClass();
            app.setCompany(company);
            app.setPositionName(position);
            app.setApplicationStatus("Pending");
            String sql
                    = "insert into job_applications "
                    + "(user_id,company,position_name,"
                    + "application_status) "
                    + "values (?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(sql);

            ps.setInt(1, LoginRegister.currentUserId);
            ps.setString(2, app.getCompany());
            ps.setString(3, app.getPositionName());
            ps.setString(4, app.getApplicationStatus());

            ps.executeUpdate();

            ps.close();
            con.close();

            Path p = Paths.get("c:\\files2\\jobapplication.dat");

            ObjectOutputStream oos = new ObjectOutputStream(new FileOutputStream(p.toFile())
            );
            oos.writeObject(app);
            oos.close();
            ObjectInputStream ois2 = new ObjectInputStream(new FileInputStream(p.toFile())
            );

            JobApplicationClass readApp = (JobApplicationClass) ois2.readObject();

            JOptionPane.showMessageDialog(
                    null,
                    "Application Submitted Successfully\n\n"
                    + "Company: "
                    + readApp.getCompany()
                    + "\nPosition: "
                    + readApp.getPositionName()
                    + "\nStatus: "
                    + readApp.getApplicationStatus(),
                    "CareerLink Jobs",
                    JOptionPane.INFORMATION_MESSAGE
            );
            ois2.close();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, e);

        }
    }//GEN-LAST:event_jButton2ActionPerformed

